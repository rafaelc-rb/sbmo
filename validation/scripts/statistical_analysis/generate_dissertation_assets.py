# 4. Strongest binary pair per CQ (phi / Fisher) table
# ---------------------------------------------------------------------------
# Hand-verified mapping from the raw Portuguese option label (base, before the
# first parenthesis) to the English class label already used elsewhere in the
# dissertation (assets/ontology/tables/frequencies.tex), so the vocabulary
# stays consistent across tables.
PT_TO_EN_BASE = {
    "Receita por suporte": "Support",
    "Entrega híbrida": "Hybrid",
    "Precificação por assinatura": "Subscription pricing",
    "Receita por assinatura": "Subscription",
    "B2C": "B2C",
    "Crescimento liderado pelo produto": "Product-led growth",
    "Plataforma bilateral": "Two-sided platform",
    "Efeito de rede cruzado": "Cross-side",
    "Gestão do ecossistema": "Ecosystem management",
    "Disrupção do ecossistema de parceiros": "Partner disruption",
    "Adoção de modelo híbrido": "Hybrid model",
    "Transformação de fluxo de receita": "Revenue-model transition",
}


def base(label):
    return label.split(" (", 1)[0].strip()


def phi_table():
    rows = read_csv(os.path.join(STATS_OUT, "strongest_binary_pairs.csv"))
    table_rows = []
    for r in rows:
        a = PT_TO_EN_BASE[base(r["OptionA"])]
        b = PT_TO_EN_BASE[base(r["OptionB"])]
        phi = float(r["Phi"])
        p = float(r["FisherP"])
        table_rows.append(f"{r['CQ']} & {a} $\\leftrightarrow$ {b} & {phi:.3f} & {fmt_p(p)} \\\\")

    table = GENERATED_HEADER + """\\begin{table}[!htb]
\\renewcommand{\\arraystretch}{1.3}
\\caption{Strongest binary association ($\\phi$ coefficient) within each competency-question pair, restricted to options selected in at least 3 and at most 28 cases; $p$-values from Fisher's exact test. Descriptive (options selected from the observed data), not independent confirmatory tests.}
\\label{tab:phi_pairs}
\\centering
\\small
\\begin{tabular}{l|l|r|r}
    \\bottomrule
    \\rowcolor{gray!50}
    \\textbf{CQ} & \\textbf{Option pair} & \\textbf{$\\phi$} & \\textbf{$p$ (Fisher)} \\\\
    \\hline
""" + "\n    ".join(table_rows) + """
    \\toprule
\\end{tabular}
\\end{table}
"""
    with open(os.path.join(TABLES, "phi_pairs.tex"), "w", encoding="utf-8") as f:
        f.write(table)
    return rows


# ---------------------------------------------------------------------------
# 5. Sensitivity analysis table
# ---------------------------------------------------------------------------
def sensitivity_table():
    full = {r["CQ"]: r for r in read_csv(os.path.join(STATS_OUT, "rv_associations.csv"))}
    sens = read_csv(os.path.join(STATS_OUT, "sensitivity_analysis.csv"))
    table_rows = []
    for r in sens:
        cq = r["CQ"]
        table_rows.append(
            f"{cq} & {float(full[cq]['RV']):.3f} & {fmt_p(full[cq]['PermutationP'])} & "
            f"{float(r['RV']):.3f} & {fmt_p(r['PermutationP'])} \\\\"
        )
    table = GENERATED_HEADER + """\\begin{table}[!htb]
\\renewcommand{\\arraystretch}{1.3}
\\caption{Sensitivity analysis: RV coefficients recomputed after retaining a single response per identified organization ($n=27$), compared with the full sample ($n=31$).}
\\label{tab:sensitivity}
\\centering
\\small
\\begin{tabular}{l|rr|rr}
    \\bottomrule
    \\rowcolor{gray!50}
     & \\multicolumn{2}{c|}{\\textbf{All cases ($n=31$)}} & \\multicolumn{2}{c}{\\textbf{Sensitivity ($n=27$)}} \\\\
    \\textbf{CQ} & \\textbf{RV} & \\textbf{$p_{perm}$} & \\textbf{RV} & \\textbf{$p_{perm}$} \\\\
    \\hline
""" + "\n    ".join(table_rows) + """
    \\toprule
\\end{tabular}
\\end{table}
"""
    with open(os.path.join(TABLES, "sensitivity.tex"), "w", encoding="utf-8") as f:
        f.write(table)


