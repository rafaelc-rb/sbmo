# 2. Knowledge self-assessment score chart (socio-demographic profile)
# ---------------------------------------------------------------------------
def knowledge_chart():
    rows = read_csv(os.path.join(STATS_OUT, "processed_data.csv"))
    scores = [r["KnowledgeScore"] for r in rows
              if r["KnowledgeScore"] and r["KnowledgeScore"] != "NA"]
    n = len(scores)
    counts = {str(s): 0 for s in range(1, 6)}
    for s in scores:
        counts[s] = counts.get(s, 0) + 1

    lines = []
    for i, score in enumerate(["1", "2", "3", "4", "5"], start=1):
        c = counts.get(score, 0)
        pct = 100 * c / n if n else 0
        lines.append(f"{pct:.1f} {i} {c}")

    tex = GENERATED_HEADER + f"""\\begin{{tikzpicture}}
\\begin{{axis}}[
    ybar,
    bar width=14pt,
    ymin=0,
    ymax={max(100 * counts.get(s, 0) / n for s in ["1","2","3","4","5"]) + 20:.0f},
    ylabel={{Percentage of respondents (\\%)}},
    xlabel={{Self-assessed knowledge (1 = low, 5 = high)}},
    symbolic x coords={{1,2,3,4,5}},
    xtick=data,
    x tick label style={{font=\\scriptsize}},
    y tick label style={{font=\\scriptsize}},
    label style={{font=\\scriptsize}},
    width=0.75\\columnwidth,
    height=5cm,
    nodes near coords,
    every node near coord/.append style={{font=\\scriptsize}},
    ymajorgrids=true,
    grid style={{gray!20}}
]
\\addplot[pattern color=hardblue, pattern=north east lines] coordinates {{
""" + " ".join(f"({s},{100*counts.get(s,0)/n:.1f})" for s in ["1","2","3","4","5"]) + """
};
\\end{axis}
\\end{tikzpicture}
"""
    with open(os.path.join(TIKZ, "knowledge_score.tex"), "w", encoding="utf-8") as f:
        f.write(tex)
    return counts, n


