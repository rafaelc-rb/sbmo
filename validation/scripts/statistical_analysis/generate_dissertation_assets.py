# 1. Respondent role category chart (socio-demographic profile)
# ---------------------------------------------------------------------------
def role_chart():
    rows = read_csv(os.path.join(SURVEY_DERIVED, "respondent_role_categories.csv"))
    n = len(rows)
    order = ["Engineering", "Leadership", "Product & Design", "Founder",
             "Technical Advisory", "Other / Analyst"]
    counts = {c: 0 for c in order}
    for r in rows:
        counts[r["respondent_role_category"]] += 1

    # ybar-inverted style (xbar), largest at top, matching revenue_sources.tex conventions
    ordered = sorted(order, key=lambda c: counts[c])  # ascending, since y dir will be reversed by listing order
    lines = []
    for i, cat in enumerate(ordered, start=1):
        pct = 100 * counts[cat] / n
        lines.append(f"{pct:.1f} {i} {counts[cat]}")
    yticklabels = ",".join("{%s}" % tex_escape(c) for c in ordered)

    tex = GENERATED_HEADER + f"""\\begin{{tikzpicture}}
\\begin{{axis}}[
    xbar,
    bar width=6pt,
    ytick=data,
    axis y line*=none,
    axis x line*=bottom,
    x tick label style={{font=\\scriptsize}},
    y tick label style={{font=\\scriptsize}},
    label style={{font=\\scriptsize}},
    xlabel={{Percentage of respondents (\\%)}},
    xmin=0,
    xmax={max(100 * v / n for v in counts.values()) + 20:.0f},
    width=0.85\\columnwidth,
    height=5cm,
    yticklabels={{{yticklabels}}},
    y=7mm,
    enlarge y limits={{abs=0.5}},
    nodes near coords,
    nodes near coords align=horizontal,
    every node near coord/.append style={{
        black, font=\\scriptsize, text opacity=1,
        fill=white, fill opacity=0.6, outer sep=\\pgflinewidth
    }},
    visualization depends on={{\\thisrow{{n}} \\as \\mycount}},
    nodes near coords={{\\pgfmathprintnumber\\pgfplotspointmeta\\% (n=\\pgfmathprintnumber[fixed,precision=0]{{\\mycount}})}}
]
\\addplot[pattern color=hardblue, pattern=north east lines] table [x=perc, y=idx, meta=perc] {{
perc idx n
""" + "\n".join(lines) + """
};
\\end{axis}
\\end{tikzpicture}
"""
    with open(os.path.join(TIKZ, "respondent_roles.tex"), "w", encoding="utf-8") as f:
        f.write(tex)
    return counts, n


