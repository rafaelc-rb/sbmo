#!/usr/bin/env python3
"""
SBMO validation — dissertation assets for the socio-demographic profile and
statistical analysis sections of Chapter 7 (Ontology Evaluation).

Reads the ANONYMIZED, already-aggregated outputs of:
  - reproduce_sbmo_analysis_fixed.r  (sbmo_analysis_output/*.csv)
  - extract_respondent_role.py       (survey-derived/respondent_role_categories.csv)
and writes ready-to-input LaTeX table/tikz fragments into
dissertation-paper/assets/ontology_evaluation/{tables,tikz}/.

No raw identifying data is read here; every input is already an anonymized,
aggregate CSV (see the two scripts above for the anonymity handling).

Usage: python3 generate_dissertation_assets.py
"""

import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
STATS_OUT = os.path.join(HERE, "sbmo_analysis_output")
VALIDATION_ROOT = os.path.dirname(os.path.dirname(HERE))  # sbmo/validation
SURVEY_DERIVED = os.path.join(VALIDATION_ROOT, "survey-derived")
SBMO_ROOT = os.path.dirname(VALIDATION_ROOT)
DISSERTATION_ROOT = os.path.dirname(SBMO_ROOT)
ASSETS = os.path.join(DISSERTATION_ROOT, "dissertation-paper", "assets", "ontology_evaluation")
TABLES = os.path.join(ASSETS, "tables")
TIKZ = os.path.join(ASSETS, "tikz")
os.makedirs(TABLES, exist_ok=True)
os.makedirs(TIKZ, exist_ok=True)

GENERATED_HEADER = (
    "% Generated by sbmo/validation/scripts/statistical_analysis/"
    "generate_dissertation_assets.py -- do not edit by hand.\n"
)


def read_csv(path):
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))


def tex_escape(s):
    """Escape LaTeX special characters in a label pulled from data/category
    names (e.g. "Product & Design" -> "Product \\& Design"). Without this,
    an unescaped '&' inside a pgfplots yticklabels list is parsed as a
    misplaced alignment tab and breaks the build."""
    return (s.replace("\\", r"\textbackslash{}")
             .replace("&", r"\&").replace("%", r"\%")
             .replace("_", r"\_").replace("#", r"\#"))


